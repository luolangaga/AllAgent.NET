  const rows = ICONS[props.name] ?? []
  const list: Pixel[] = []
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      if (row[x] === '#') {
        list.push({ x, y, key: `${x}-${y}` })
      }
    }
  })
