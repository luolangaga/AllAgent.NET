using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace LanAgent.ToolGenerator;

[Generator]
public sealed class AgentToolGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidTool = new("LA001", "Unsupported AgentTool contract",
        "AgentTool '{0}' must be a public instance method on a non-generic partial class, return Task<ToolResult>, and use string, int, bool, described primitive records, arrays of these types or CancellationToken parameters with descriptions", "LanAgent", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var methods = context.SyntaxProvider.ForAttributeWithMetadataName("LanAgent.Core.Tools.AgentToolAttribute",
            (node, _) => node is MethodDeclarationSyntax, (ctx, _) => (IMethodSymbol)ctx.TargetSymbol).Collect();
        context.RegisterSourceOutput(methods, (output, symbols) =>
        {
            foreach (var group in symbols.GroupBy(m => m.ContainingType, SymbolEqualityComparer.Default))
            {
                var type = group.First().ContainingType;
                var list = group.ToList();
                var invalid = false;
                foreach (var m in list)
                {
                    if (m.DeclaredAccessibility != Accessibility.Public || m.IsStatic || type.IsGenericType || type.ContainingType != null ||
                        !type.DeclaringSyntaxReferences.Any(r => r.GetSyntax() is ClassDeclarationSyntax c && c.Modifiers.Any(SyntaxKind.PartialKeyword)) ||
                        m.ReturnType.ToDisplayString() != "System.Threading.Tasks.Task<LanAgent.Core.Tools.ToolResult>" || Description(m) == null ||
                        m.Parameters.Any(p => p.RefKind != RefKind.None || (p.Type.ToDisplayString() != "System.Threading.CancellationToken" && (JsonType(p.Type) == null || Description(p) == null))))
                    {
                        output.ReportDiagnostic(Diagnostic.Create(InvalidTool, m.Locations.FirstOrDefault(), m.Name));
                        invalid = true;
                    }
                }
                if (invalid) continue;
                var code = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace ").Append(type.ContainingNamespace.ToDisplayString()).Append(";\npublic partial class ").Append(type.Name).Append(" : global::LanAgent.Core.Tools.IAgentToolSet {\n");
                code.Append("public global::System.Collections.Generic.IReadOnlyList<global::LanAgent.Core.Tools.AgentToolDescriptor> Definitions { get; } = new global::LanAgent.Core.Tools.AgentToolDescriptor[] {\n");
                foreach (var m in list)
                {
                    var attr = m.GetAttributes().First(a => a.AttributeClass?.ToDisplayString() == "LanAgent.Core.Tools.AgentToolAttribute");
                    var name = (string)attr.ConstructorArguments[0].Value!;
                    var risk = attr.NamedArguments.FirstOrDefault(a => a.Key == "Risk").Value.Value ?? 0;
                    var ps = m.Parameters.Where(p => p.Type.ToDisplayString() != "System.Threading.CancellationToken").ToList();
                    var props = ps.Select(p => QuoteJson(p.Name) + ":" + Schema(p.Type, Description(p)!));
                    var schema = "{\"type\":\"object\",\"additionalProperties\":false,\"properties\":{" + string.Join(",", props) + "},\"required\":[" + string.Join(",", ps.Where(p => !p.HasExplicitDefaultValue).Select(p => QuoteJson(p.Name))) + "]}";
                    code.Append("new(").Append(Literal(name)).Append(", ").Append(Literal(Description(m)!)).Append(", global::System.Text.Json.JsonSerializer.Deserialize<global::System.Text.Json.JsonElement>(").Append(Literal(schema)).Append("), (global::LanAgent.Core.Tools.ToolRisk)").Append(risk).Append("),\n");
                }
                code.Append("};\npublic async global::System.Threading.Tasks.ValueTask<global::LanAgent.Core.Tools.ToolResult> InvokeAsync(string name, global::System.Text.Json.JsonElement arguments, global::System.Threading.CancellationToken ct) {\nswitch(name) {\n");
                foreach (var m in list)
                {
                    var name = (string)m.GetAttributes().First(a => a.AttributeClass?.ToDisplayString() == "LanAgent.Core.Tools.AgentToolAttribute").ConstructorArguments[0].Value!;
                    code.Append("case ").Append(Literal(name)).Append(": return await ").Append(m.Name).Append('(');
                    code.Append(string.Join(", ", m.Parameters.Select(p => p.Type.ToDisplayString() == "System.Threading.CancellationToken" ? "ct" :
                        "global::LanAgent.Core.Tools.ToolArguments.Get<" + p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ">(arguments, " + Literal(p.Name) + (p.HasExplicitDefaultValue ? ", " + Default(p) : "") + ")")));
                    code.Append(").ConfigureAwait(false);\n");
                }
                code.Append("default: return global::LanAgent.Core.Tools.ToolResult.Failure(\"Unknown tool\"); } } }\n");
                output.AddSource(type.Name + ".AgentTools.g.cs", code.ToString());
            }
        });
    }

    private static string? Description(ISymbol symbol) => symbol.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == "System.ComponentModel.DescriptionAttribute")?.ConstructorArguments.FirstOrDefault().Value as string;
    private static string? JsonType(ITypeSymbol type) => type.SpecialType switch
    {
        SpecialType.System_String => "string", SpecialType.System_Int32 => "integer", SpecialType.System_Boolean => "boolean",
        _ => type is IArrayTypeSymbol array && JsonType(array.ElementType) != null ? "array" :
            type is INamedTypeSymbol named && named.TypeKind == TypeKind.Class && named.IsRecord &&
            Properties(named).Any() && Properties(named).All(p => Description(p) != null && p.Type.SpecialType is SpecialType.System_String or SpecialType.System_Int32 or SpecialType.System_Boolean) ? "object" : null
    };
    private static IEnumerable<IPropertySymbol> Properties(INamedTypeSymbol type) => type.GetMembers().OfType<IPropertySymbol>()
        .Where(p => !p.IsStatic && !p.IsIndexer && p.DeclaredAccessibility == Accessibility.Public && p.GetMethod != null && p.SetMethod != null);
    private static string Schema(ITypeSymbol type, string description)
    {
        var result = "{\"type\":" + QuoteJson(JsonType(type)!) + ",\"description\":" + QuoteJson(description);
        if (type is IArrayTypeSymbol array) result += ",\"items\":" + Schema(array.ElementType, "Array entry");
        else if (JsonType(type) == "object")
        {
            var properties = Properties((INamedTypeSymbol)type).ToArray();
            result += ",\"additionalProperties\":false,\"properties\":{" + string.Join(",", properties.Select(p => QuoteJson(p.Name) + ":" + Schema(p.Type, Description(p)!))) +
                "},\"required\":[" + string.Join(",", properties.Select(p => QuoteJson(p.Name))) + "]";
        }
        return result + "}";
    }
    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, true);
    private static string QuoteJson(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "\\r").Replace("\n", "\\n").Replace("\t", "\\t") + "\"";
    private static string Default(IParameterSymbol p) => p.ExplicitDefaultValue switch
    {
        null => "default!", string s => Literal(s), bool b => b ? "true" : "false", _ => Convert.ToString(p.ExplicitDefaultValue, System.Globalization.CultureInfo.InvariantCulture)!
    };
}
